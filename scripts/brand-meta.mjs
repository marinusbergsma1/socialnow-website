/**
 * Return plain-text metadata for an exact, unprefixed route and language.
 * @param {string} route One of /, /het-os, /team, /diensten, /prijzen, /contact, /vacatures.
 * @param {string} language One of en, nl, de, fr, es, it, pt, pl, sv, da.
 * @returns {{ title: string, description: string } | null}
 */
export function brandMeta(route, language) {
  if (typeof route !== 'string' || typeof language !== 'string') return null;
  if (!Object.hasOwn(metadata, language)) return null;
  const localized = metadata[language];
  if (!Object.hasOwn(localized, route)) return null;
  const [title, description] = localized[route];
  return { title, description };
}
